// Single source for the Cloudflare Worker deployment: wrangler.jsonc, worker/routes.ts,
// and the dist/_headers and dist/_redirects files applied to static asset responses.
import { HOMEPAGE_LINK_HEADER, agentDocuments } from "../src/agent/documents.ts";
import { markdownPages, redirects, routePaths } from "../src/domain/route.ts";

type HeaderValues = Record<string, string>;

const documents = agentDocuments();
const markdown = documents.find(({ path }) => path.endsWith(".md"));
if (!markdown) throw new Error("agent document registry has no markdown document");

const headerRules: Record<string, HeaderValues> = {
	"/": {
		Vary: "Accept",
		Link: HOMEPAGE_LINK_HEADER,
		"Content-Signal": "search=yes, ai-input=yes, ai-train=yes",
	},
	"/*.md": { "Content-Type": markdown.contentType, Vary: "Accept" },
	...Object.fromEntries(
		documents
			.filter(({ path }) => !path.endsWith(".md"))
			.map(({ path, contentType }) => [path, { "Content-Type": contentType }]),
	),
};

// html_handling is "none", so the homepage and every HTML route map to an explicit file.
const rewrites: Record<string, string> = {
	...Object.fromEntries(routePaths.map((source) => [source, "/index.html"])),
	...Object.fromEntries(
		["developers", "about", "contact", "privacy"].map((name) => [`/${name}`, `/${name}.html`]),
	),
};

const workerPaths = new Set([...Object.keys(redirects), ...markdownPages().keys()]);

/** Paths the Worker answers before static assets: API, redirects, and Markdown negotiation. */
const runWorkerFirst = [
	"/api/*",
	"/.well-known/mcp",
	"/.well-known/mcp/",
	...[...workerPaths].flatMap((path) => (path === "/" ? [path] : [path, `${path}/`])),
];

export const wranglerConfig = `// Generated by scripts/cloudflare.ts. Do not edit.
${JSON.stringify(
	{
		$schema: "node_modules/wrangler/config-schema.json",
		name: "localstudio",
		main: "worker/index.ts",
		compatibility_date: "2026-10-20",
		workers_dev: true,
		assets: {
			directory: "dist",
			binding: "ASSETS",
			html_handling: "none",
			not_found_handling: "404-page",
			run_worker_first: runWorkerFirst,
		},
	},
	null,
	"\t",
)}
`;

export const workerRoutes = `// Generated by scripts/cloudflare.ts. Do not edit.
export const redirects: Readonly<Record<string, string>> = ${JSON.stringify(redirects)};
export const markdownByPath: Readonly<Record<string, string>> = ${JSON.stringify(Object.fromEntries(markdownPages()))};
export const rewrites: Readonly<Record<string, string>> = ${JSON.stringify(rewrites)};
export const headersByPath: Readonly<Record<string, Readonly<Record<string, string>>>> = ${JSON.stringify(
	Object.fromEntries(Object.entries(headerRules).filter(([source]) => !source.includes("*"))),
)};
`;

export const headersFile = Object.entries(headerRules)
	.map(
		([source, headers]) =>
			`${source}\n${Object.entries(headers)
				.map(([name, value]) => `\t${name}: ${value}\n`)
				.join("")}`,
	)
	.join("\n");

export const redirectsFile = Object.entries(rewrites)
	.map(([source, destination]) => `${source} ${destination} 200\n`)
	.join("");
